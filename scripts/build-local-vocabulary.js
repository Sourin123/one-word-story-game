import fs from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const frequencyEntries = require('subtlex-word-frequencies');
const commonWords = [...new Set(
  frequencyEntries
    .slice(0, 20000)
    .map(entry => entry.word.toLowerCase())
    .filter(word => /^[a-z]{3,12}$/.test(word) && /[aeiouy]/.test(word))
)];
const words = commonWords.slice(0, 12000);

if (words.length < 10001) {
  throw new Error(`Expected more than 10,000 unique words, found ${words.length}.`);
}

const formatWords = words => {
  const lines = [];
  for (let index = 0; index < words.length; index += 10) {
    lines.push(`    ${words.slice(index, index + 10).map(word => `'${word}'`).join(', ')}`);
  }
  return `[\n${lines.join(',\n')}\n  ]`;
};

const output = `// Generated by scripts/build-local-vocabulary.js from the ISC-licensed subtlex-word-frequencies package.
// Derived from the 12,000 most frequent eligible spoken-English words; role buckets are heuristic.
const words = ${formatWords(words)};
const functionWords = new Set([
  'a', 'about', 'after', 'again', 'all', 'also', 'although', 'am', 'an', 'and',
  'any', 'are', 'as', 'at', 'be', 'because', 'been', 'before', 'being', 'below',
  'between', 'both', 'but', 'by', 'can', 'could', 'did', 'do', 'does', 'doing',
  'down', 'during', 'each', 'few', 'for', 'from', 'further', 'had', 'has', 'have',
  'he', 'her', 'here', 'hers', 'him', 'his', 'how', 'i', 'if', 'in', 'into', 'is',
  'it', 'its', 'just', 'me', 'more', 'most', 'my', 'no', 'nor', 'not', 'of', 'off',
  'on', 'once', 'only', 'or', 'other', 'our', 'out', 'over', 'own', 'same', 'she',
  'should', 'so', 'some', 'such', 'than', 'that', 'the', 'their', 'them', 'then',
  'there', 'these', 'they', 'this', 'those', 'through', 'to', 'too', 'under',
  'until', 'up', 'very', 'was', 'we', 'were', 'what', 'when', 'where', 'which',
  'while', 'who', 'whom', 'why', 'will', 'with', 'would', 'you', 'your'
]);
const adverbs = words.filter(word => word.endsWith('ly'));
const verbs = words.filter(word =>
  !functionWords.has(word) && /(ed|ing|ate|en|fy|ise|ize)$/.test(word)
);
const adjectives = words.filter(word =>
  !functionWords.has(word) && /(able|ible|al|ful|ic|ive|less|ous|y|ed|ing|ish|ary|ent|ant)$/.test(word)
);
const nonNounWords = new Set([...functionWords, ...adverbs, ...verbs, ...adjectives]);
const nouns = words.filter(word => !nonNounWords.has(word));

export const EXPANDED_LOCAL_VOCABULARY = {
  words,
  adjectives,
  verbs,
  adverbs,
  nouns
};
`;

fs.writeFileSync(new URL('../src/localBotVocabulary.js', import.meta.url), output);
console.log(`Generated ${words.length.toLocaleString()} unique offline words.`);
